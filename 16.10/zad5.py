
n = int(input("Въведи число от 1 до 7: "))

if n == 1:
    print("Ден 1 е понеделник")
elif n == 2:
    print("Ден 2 е вторник")
elif n == 3:
    print("Ден 3 е сряда")
elif n == 4:
    print("Ден 4 е четвъртък")
elif n == 5:
    print("Ден 5 е петък")
elif n == 6:
    print("Ден 6 е събота")
elif n == 7:
    print("Ден 7 е неделя")
else:
    print("Невалидно число")
